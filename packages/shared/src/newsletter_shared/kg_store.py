"""知識圖譜（Postgres，由環境變數 NEWSLETTER_DATABASE_URL 指定）的資料表與判讀規則，writer（寫入、產生背景）與 web-server（唯讀的脈絡圖）共用。

寫入只在 writer 的 newsletter_writer.kg；這裡放兩邊都要、而且必須一致的東西：
資料表定義、連線方式、實體名稱的正規化（mentions.key）、事件狀態（active／disputed／invalid）、來源數算法，
以及給 devtools 快照與 SQLite 匯入用的 dump／load。
"""
from __future__ import annotations

import os
import unicodedata

import psycopg

ENV = "NEWSLETTER_DATABASE_URL"

SCHEMA = """
CREATE TABLE IF NOT EXISTS items(uid TEXT PRIMARY KEY, date TEXT, title TEXT, url TEXT, source TEXT, version INTEGER);
CREATE TABLE IF NOT EXISTS events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid TEXT, date TEXT, summary TEXT, quote TEXT,
                                  related INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS mentions(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event BIGINT, key TEXT, name TEXT, type TEXT);
CREATE TABLE IF NOT EXISTS links(src BIGINT, dst BIGINT, kind TEXT, quote TEXT, date TEXT);
CREATE INDEX IF NOT EXISTS mentions_key ON mentions(key);
CREATE INDEX IF NOT EXISTS events_uid ON events(uid);
CREATE INDEX IF NOT EXISTS links_dst ON links(dst);
CREATE INDEX IF NOT EXISTS mentions_event ON mentions(event);
CREATE INDEX IF NOT EXISTS links_src ON links(src);
CREATE INDEX IF NOT EXISTS events_date ON events(date);
"""

TYPES = {"org", "person", "product", "place", "other"}
KINDS = {"same", "follow", "contradict", "retract"}
STATUSES = ("active", "disputed", "invalid")
TABLES = ("items", "events", "mentions", "links")
_ORDER = {"items": "uid", "events": "id", "mentions": "id", "links": "src, dst, kind, date"}


def norm(text: str) -> str:
    """比對用：全半形、大小寫、空白與標點都不算。也是實體的 key（mentions.key）。"""
    return "".join(ch for ch in unicodedata.normalize("NFKC", text).casefold() if ch.isalnum())


def connect() -> psycopg.Connection:
    """連線並建立資料表（autocommit；寫入端需要交易時用 with con.transaction():）。"""
    url = os.environ.get(ENV, "").strip()
    if not url:
        raise RuntimeError(f"缺少環境變數 {ENV}（Postgres 連線字串）")
    con = psycopg.connect(url, autocommit=True, connect_timeout=5)
    try:
        con.execute(SCHEMA)
    except BaseException:
        con.close()
        raise
    return con


def open_readonly() -> psycopg.Connection | None:
    """唯讀開啟；未設定 NEWSLETTER_DATABASE_URL 或還沒建過表時回傳 None。"""
    url = os.environ.get(ENV, "").strip()
    if not url:
        return None
    con = psycopg.connect(url, autocommit=True, connect_timeout=5)
    try:
        con.execute("SET default_transaction_read_only = on")
        row = con.execute("SELECT to_regclass('events')").fetchone()
        if row is None or row[0] is None:
            con.close()
            return None
    except BaseException:
        con.close()
        raise
    return con


def statuses(con: psycopg.Connection, ids: list[int], flags: dict[str, str]) -> dict[int, str]:
    """active／disputed／invalid。使用者的判定優先；被標 wrong 的則對別則的矛盾、撤回不算。
    一個來源矛盾＝有爭議；明確撤回，或兩個以上來源矛盾＝失效。"""
    if not ids:
        return {}
    uid_of = dict(con.execute("SELECT id, uid FROM events WHERE id = ANY(%s)", (ids,)).fetchall())
    out = {eid: "invalid" if flags.get(uid_of.get(eid)) == "wrong" else "active" for eid in ids}
    against: dict[int, dict[str, set]] = {}
    for dst, kind, src_uid, source in con.execute(
            """SELECT l.dst, l.kind, e.uid, i.source FROM links l JOIN events e ON e.id=l.src JOIN items i ON i.uid=e.uid
               WHERE l.dst = ANY(%s) AND l.kind IN ('contradict', 'retract')""", (ids,)):
        if flags.get(src_uid) != "wrong":
            against.setdefault(dst, {}).setdefault(kind, set()).add(source)
    for eid, kinds in against.items():
        if out[eid] == "invalid":
            continue
        if kinds.get("retract") or len(kinds.get("contradict", ())) >= 2:
            out[eid] = "invalid"
        elif kinds.get("contradict"):
            out[eid] = "disputed"
    out.update({eid: "active" for eid, uid in uid_of.items() if flags.get(uid) == "trusted"})
    return out


def sources(con: psycopg.Connection, eid: int, own: str) -> int:
    """報導這個事件的來源數：自己的來源加上 same 連到的其他來源。"""
    return sources_many(con, {eid: own})[eid]


def sources_many(con: psycopg.Connection, own: dict[int, str]) -> dict[int, int]:
    """sources() 的批次版：{事件 id: 自己的來源} → {事件 id: 來源數}，一次查詢。"""
    if not own:
        return {}
    ids = list(own)
    found: dict[int, set[str]] = {eid: {src} for eid, src in own.items()}
    for eid, source in con.execute(
            """SELECT x.eid, i.source FROM (
                   SELECT src AS eid, dst AS other FROM links WHERE kind='same' AND src = ANY(%s)
                   UNION ALL
                   SELECT dst, src FROM links WHERE kind='same' AND dst = ANY(%s)) x
               JOIN events e ON e.id = x.other JOIN items i ON i.uid = e.uid""", (ids, ids)):
        found[eid].add(source)
    return {eid: len(srcs) for eid, srcs in found.items()}


def dump(con: psycopg.Connection) -> dict[str, list[list]]:
    """匯出四張表為可 JSON 化的 {表名: [[欄位...], ...]}，順序穩定。"""
    return {table: [list(row) for row in con.execute(f"SELECT * FROM {table} ORDER BY {_ORDER[table]}")]
            for table in TABLES}


def load(con: psycopg.Connection, data: dict[str, list[list]]) -> None:
    """在單一交易內清空並載入四張表，最後將 events.id 與 mentions.id 的序號設成 MAX(id)+1。"""
    with con.transaction():
        for table in TABLES:
            con.execute(f"DELETE FROM {table}")
        with con.cursor() as cur:
            for table in TABLES:
                rows = data.get(table) or []
                if rows:
                    marks = ",".join(["%s"] * len(rows[0]))
                    cur.executemany(f"INSERT INTO {table} VALUES ({marks})", rows)
        for table in ("events", "mentions"):
            con.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), COALESCE(MAX(id), 0) + 1, false) FROM {table}")
